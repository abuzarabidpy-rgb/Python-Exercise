# Lambda_Expression:     #(anonymous function)

def add(a, b):
    return a+b
print(add(5, 6))

# Lambda_Expressions:

add_num = lambda a,b : a+b
print(add_num(9, 7))

multiply_num = lambda a,b : a*b
print(multiply_num(6, 7))

subtract_num = lambda a,b : a-b
print(subtract_num(15, 7))